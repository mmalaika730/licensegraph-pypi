#!/usr/bin/env python3
"""
make_rules_ttl.py | turns Dataset/curated/compatibility_rules.csv (+ compatibility_sources.csv)
into Ontology/compatibility_rules.ttl, the schema-level rule knowledge used by the conflict rule.

Usage: python3 make_rules_ttl.py --rules ../Dataset/curated/compatibility_rules.csv \
                                  --sources ../Dataset/curated/compatibility_sources.csv \
                                  --out compatibility_rules.ttl
"""
import argparse
import csv

CATEGORIES = {"PermissiveLicense", "ProprietaryLicense", "WeakCopyleftLicense", "StrongCopyleftLicense",
              "NetworkCopyleftLicense", "UnknownLicense", "License"}
VERDICTS = {"Compatible", "Incompatible", "Conditional"}


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rules", required=True)
    ap.add_argument("--sources", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    sources = {r["source_key"]: r for r in csv.DictReader(open(a.sources, encoding="utf-8"))}
    lines = ["@prefix lg:   <http://example.org/licensegraph#> .",
             "@prefix rule: <http://example.org/licensegraph/rule/> .",
             "@prefix src:  <http://example.org/licensegraph/source/> .",
             "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
             "@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .", "",
             "# GENERATED by make_rules_ttl.py from Dataset/curated/compatibility_rules.csv. Edit the CSV, not this file.", ""]
    for k, s in sources.items():
        lines += [f"src:{k} a lg:Source ; rdfs:label {lit(s['title'])} ; lg:sourcePublisher {lit(s['publisher'])} ;",
                  f"    lg:sourceUrl {lit(s['url'])}^^xsd:anyURI ; lg:sourceAccessed {lit(s['accessed'] + 'T00:00:00')}^^xsd:dateTime .", ""]
    n = 0
    for r in csv.DictReader(open(a.rules, encoding="utf-8")):
        pc = r["project_category"].replace("LicenseDependencyUnknown", "License")
        assert pc in CATEGORIES and r["dependency_category"] in CATEGORIES, r
        assert r["verdict"] in VERDICTS, r
        keys = [k.strip() for k in r["source_key"].split(";") if k.strip()]
        for k in keys:
            assert k in sources, f"unknown source {k}"
        parts = [f"rule:{r['rule_id']} a lg:CompatibilityRule",
                 f"lg:projectCategory lg:{pc}", f"lg:dependencyCategory lg:{r['dependency_category']}",
                 f"lg:verdict lg:{r['verdict']}", f"lg:ruleStatus {lit(r['source_status'])}",
                 f"rdfs:comment {lit(r['rationale'])}"]
        if keys:
            parts.append("lg:ruleSource " + ", ".join(f"src:{k}" for k in keys))
        lines.append(" ;\n    ".join(parts) + " .\n")
        n += 1
    open(a.out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {n} rules and {len(sources)} sources to {a.out}")


if __name__ == "__main__":
    main()
